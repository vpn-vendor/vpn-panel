func TestSudoers(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{
			name: "закомментировано, чужой пользователь, Defaults, без ALL",
			files: map[string]string{sudoersFile: "@includedir /etc/sudoers.d\n" +
				"www-data gw1 = (root) NOPASSWD: /usr/bin/id\n" +
				"#www-data ALL=(ALL) NOPASSWD: ALL\n" +
				"  # www-data ALL=(ALL) NOPASSWD: ALL\n" +
				"www-data2 ALL=(ALL) NOPASSWD: ALL\n" +
				"Defaults:www-data !requiretty\n"},
		},
		{
			name: "sudo не читает файлы с точкой и «~»",
			files: map[string]string{
				sudoersFile:                "@includedir /etc/sudoers.d\n",
				"/etc/sudoers.d/web.bak":   "www-data ALL=(ALL) NOPASSWD: ALL\n",
				"/etc/sudoers.d/web~":      "www-data ALL=(ALL) NOPASSWD: ALL\n",
				"/etc/sudoers.d/www-data/": "",
			},
		},
		{
			name: "каталог не подключён",
			files: map[string]string{
				sudoersFile:          "root ALL=(ALL:ALL) ALL\n",
				"/etc/sudoers.d/web": "www-data ALL=(ALL) NOPASSWD: ALL\n",
			},
		},
		{
			name: "узкое правило на один сценарий — не полный root",
			files: map[string]string{
				sudoersFile: "www-data ALL=(root) NOPASSWD: /usr/local/bin/renew.sh\n" +
					"www-data ALL=(root) NOPASSWD: /bin/systemctl restart telegram_bot\n",
			},
		},
		{
			name: "строки старого скрипта",
			files: map[string]string{
				sudoersFile: "www-data ALL=(ALL) NOPASSWD: ALL\n",
			},
			want: []string{sudoersFile},
		},
		{
			name: "группа и перенос строки",
			files: map[string]string{
				sudoersFile: "#includedir /etc/sudoers.d\n",
				"/etc/sudoers.d/web": "%www-data ALL=(ALL) \\\n" +
					"    NOPASSWD: /bin/systemctl\n",
			},
			want: []string{"/etc/sudoers.d/web"},
		},
		{
			name: "список пользователей, include по относительному пути и петля",
			files: map[string]string{
				sudoersFile:       "@include extra\n",
				"/etc/extra":      "#include /etc/sudoers\nadmin,www-data ALL = (ALL) ALL\n",
				"/etc/sudoers.d/": "",
			},
			want: []string{"/etc/extra"},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := host{root: fixture{files: tc.files}.build(t)}.sudoHits()
			if !reflect.DeepEqual(got, tc.want) {
				t.Fatalf("получено %q, ожидали %q", got, tc.want)
			}
		})
	}
}

