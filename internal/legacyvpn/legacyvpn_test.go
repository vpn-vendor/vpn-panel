type fixture struct {
	files map[string]string
	perms map[string]os.FileMode
}

func (f fixture) build(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	for p, body := range f.files {
		full := filepath.Join(root, p)
		if p[len(p)-1] == '/' {
			if err := os.MkdirAll(full, 0o755); err != nil { //nolint:gosec
				t.Fatal(err)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil { //nolint:gosec
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil { //nolint:gosec
			t.Fatal(err)
		}
	}
	for p, m := range f.perms {
		if err := os.Chmod(filepath.Join(root, p), m); err != nil { //nolint:gosec
			t.Fatal(err)
		}
	}
	return root
}

func with(parts ...map[string]string) map[string]string {
	out := map[string]string{}
	for _, p := range parts {
		maps.Copy(out, p)
	}
	return out
}

