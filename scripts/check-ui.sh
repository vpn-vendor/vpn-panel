#!/usr/bin/env bash
# Страж интерфейса: правило, которое проверяет только человек, соблюдается,
# пока он помнит. Поэтому проверяет машина.
#
# Шестнадцать механических проверок правил интерфейса. Проверки сценариев и
# стилей (8–12) страж сначала доказывает на себе: фикстуры с внесённым
# нарушением обязаны краснеть, чистая — нет.
#
#   ./scripts/check-ui.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

VIEWS="resources/views"
CSS="public/css"
JS="public/js"

fail=0
say() { echo "  ✗ $1" >&2; fail=1; }

# --- 1. Инлайновый стиль ---------------------------------------------------
# Политика содержимого запрещает его механически, но браузер узнает об этом
# у клиента. Гейт обязан узнать раньше.
out="$(grep -rnE '\sstyle="' "$VIEWS" 2>/dev/null || true)"
if [ -n "$out" ]; then
    say "инлайновый стиль в разметке (запрещён строгой политикой содержимого):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi

# --- 2. Инлайновый обработчик ---------------------------------------------
out="$(grep -rnE '\son(click|change|input|submit|load|focus|blur|keyup|keydown|mouseover)=' "$VIEWS" 2>/dev/null || true)"
if [ -n "$out" ]; then
    say "инлайновый обработчик события (связывание только через addEventListener):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi

# Граница палитры — конец ведущих блоков токенов (:root и :root[data-theme]).
# Ищется по структуре, а не по комментарию: в публичной сборке комментарии
# статики сняты, и маркер-комментарий пропал бы вместе с проверками.
token_end() {
    perl -0777 -ne '
        s{/\*.*?\*/}{ (my $c = $&) =~ s/[^\n]//g; $c }gse;
        my ($depth, $sel, $line, $end) = (0, "", 1, 0);
        for my $ch (split //) {
            $line++ if $ch eq "\n";
            if ($ch eq "{") { $depth++; next; }
            if ($ch eq "}") {
                $depth--;
                if ($depth == 0) {
                    if ($sel =~ /^\s*:root(\[data-theme="[\w-]+"\])?\s*$/) { $end = $line; }
                    elsif ($end) { last; }
                    $sel = "";
                }
                next;
            }
            $sel .= $ch if $depth == 0;
        }
        print $end + 1 if $end;
    ' "$1"
}

# --- 3. Цвет мимо токенов --------------------------------------------------
# Токены объявляются в начале app.css внутри :root-блоков; всё остальное
# обязано ссылаться на них через var(). Иначе тёмная тема однажды станет
# нечитаемой в одном отдельно взятом месте.
if [ -f "$CSS/app.css" ]; then
    # Границу блока токенов отмечает явный маркер, а не счёт строк: счёт
    # строк ломается от любой правки палитры, и страж начинает смотреть не
    # туда — молча.
    marker="$(token_end "$CSS/app.css")"
    if [ -z "$marker" ]; then
        say "в стилях не найдены блоки токенов :root — границу палитры проверить нечем"
    else
        out="$(tail -n +"$marker" "$CSS/app.css" | grep -nE '#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(' || true)"
        if [ -n "$out" ]; then
            say "цвет мимо токенов в стилях (после блоков токенов только var(--…)):"
            printf '%s\n' "$out" | head -10 | sed 's/^/      /' >&2
        fi
    fi
fi

# --- 4. Свойства, которые браузер пересчитывает каждый кадр ----------------
# Это и есть просадки кадров, а не «медленный стек».
if [ -d "$CSS" ]; then
    out="$(grep -rnE 'backdrop-filter|filter:\s*blur|transition:\s*all|(transition|animation):[^;]*\b(width|height|top|left|right|bottom|margin|padding|inset)\b' "$CSS" 2>/dev/null || true)"
if [ -n "$out" ]; then
        say "свойство, требующее пересчёта слоя каждый кадр (бюджет кадра):"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
    fi
fi

# --- 5. Словарь разделов ---------------------------------------------------
# Термин латиницей, объяснение по-русски. Перевод термина делает интерфейс
# МЕНЕЕ понятным: «DNS» пользователь видел в договоре с провайдером,
# «Имена в сети» — нигде.
#
# Проверяется НАЗВАНИЕ раздела, а не слова вообще: в объясняющей подписи
# «Защищённый канал офиса» те же слова уместны и нужны. Первая редакция
# запрещала фразу везде и ругалась на собственный комментарий — правило,
# которое нельзя объяснить, ловит не то.
BANNED='Выдача адресов|Имена в сети|Приоритет трафика|Защищённый канал'
out="$(grep -rnE "nav-title\">($BANNED)<" "$VIEWS" 2>/dev/null || true)"
if [ -n "$out" ]; then
    say "переведённый термин в названии раздела меню (термин латиницей, объяснение по-русски):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi
out="$(grep -rnE "page\(ctx, \"($BANNED)\"" app/ 2>/dev/null || true)"
if [ -n "$out" ]; then
    say "переведённый термин в заголовке страницы (термин латиницей, объяснение по-русски):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
    echo "      → DHCP, DNS, QoS, VPN — с русской подписью под заголовком" >&2
fi

# --- 6. Внешний ресурс -----------------------------------------------------
# Запрещена ЗАГРУЗКА извне: скрипт, картинка, стиль, шрифт. Обычная ссылка
# <a href="https://…"> ничего не загружает — это переход, который человек
# делает сам, и авторство продукта указывается именно так. Первая редакция
# запрещала любую внешнюю ссылку и путала переход с загрузкой.
# Панель работает в сети без интернета: всё только локально.
out="$(grep -rnE 'src="(https?:)?//|<link[^>]*href="(https?:)?//|url\("?(https?:)?//' "$VIEWS" "$CSS" "$JS" 2>/dev/null || true)"
if [ -n "$out" ]; then
    say "ссылка на внешний ресурс (панель работает без интернета — всё только локально):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi
out="$(grep -rnE '@import\s+url\(\s*["'"'"']?(https?:)?//' "$CSS" 2>/dev/null || true)"
if [ -n "$out" ]; then
    say "внешний импорт в стилях (всё только локально):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi

# --- 7. Открытые страницы без опознавательных знаков -----------------------
# Страницы, открытые без входа (pc/, скорость до сервера, вход, мастер),
# видит любой в сети офиса. Название продукта, его знак и значок сайта на них
# — это отпечаток, по которому продукт опознаётся и ищется в сети. Открытыми
# считаются все шаблоны, которые зовут нейтральную шапку, — список не ведётся
# руками и не отстанет от новой страницы.
BRAND='vpn-panel|vpn-vendor|VPN Panel|brand-(name|by|mark|version)|chrome-brand|pro-pill'
# Имя консольной команды входа — функциональная подсказка администратору.
# Шаблон входа показывает его ТОЛЬКО тому, кто открыл страницу на самом
# сервере; постороннему в сети офиса — нет. Статическая проверка условий не
# видит, поэтому само это правило держит тест отрисовки открытых страниц.
# Здесь исключение — только по полному имени и до проверки: знак рядом не
# пройдёт.
ALLOW_OPEN='vpn-panel-code'
# Файл оболочки исключён из этого списка: в нём живёт и оболочка за входом,
# где бренду место, а его нейтральные блоки проверяются ниже по одному.
# Первая редакция включала его целиком — «auth-top» сама зовёт нейтральную
# шапку — и объявляла открытой страницей всю панель.
open_tpls="$(grep -lE 'template "(plain-head|auth-top)"' "$VIEWS"/*.tmpl 2>/dev/null | grep -v '/partials\.tmpl$' || true)"
for f in $open_tpls; do
    out="$(sed -E "s/$ALLOW_OPEN//g" "$f" | grep -nE "$BRAND" || true)"
    if [ -n "$out" ]; then
        say "опознавательный знак на открытой странице $f:"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
    fi
done
for blk in plain-head auth-top auth-bottom; do
    body="$(awk -v b="$blk" '$0 ~ "define \"" b "\"" {f=1} f {print} f && /^\{\{ end \}\}$/ {exit}' "$VIEWS/partials.tmpl")"
    if [ -z "$body" ]; then
        say "в оболочке нет блока «$blk» — открытые страницы проверить нечем"
        continue
    fi
    out="$(printf '%s\n' "$body" | grep -nE "$BRAND|/public/[a-z-]+\.svg" || true)"
    if [ -n "$out" ]; then
        say "опознавательный знак в нейтральной шапке «$blk»:"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
    fi
done
# Страница ошибки защиты форм отдаётся любому, минуя шаблоны.
out="$(grep -nE '<(link|title|img|body|h1)[^>]*' app/http/middleware/csrf_guard.go | grep -E "$BRAND|/public/[a-z-]+\.svg" || true)"
if [ -n "$out" ]; then
    say "опознавательный знак на странице ошибки защиты форм:"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi

# --- 8–10. Память страницы: сценарии -----------------------------------------
# Страница однажды пересоздавала полотна по событию интерфейса — десятки тысяч
# полотен за секунды, гигабайты ОЗУ при маленькой куче сценария: память
# полотен живёт вне кучи. Предохранитель в islands.js ловит это в браузере;
# страж — до браузера.
#   8  разметка строкой (innerHTML и родня): пересоздаёт поддерево целиком,
#      вместе с полотнами и раскрытыми блоками — так цикл и замкнулся;
#   9  полотно создаёт сценарий: полотно отдаёт сервер в атоме, остров только
#      находит своё — «вне инициализации» проверять нечем и незачем;
#   10 остров подписывается, заводит таймер или кадр мимо ядра: такой вход
#      предохранитель остановить не может.
# Строки-комментарии не проверяются: правило обязано уметь себя объяснить.
scan_scripts() {
    local dir="$1" f
    local code='^[^:]+:[0-9]+:[[:space:]]*(//|/\*|\*)'
    grep -rnE 'innerHTML[[:space:]]*\+?=|outerHTML[[:space:]]*=|insertAdjacentHTML' "$dir" --include='*.js' 2>/dev/null \
        | grep -vE "$code" | sed 's/^/8:/' || true
    grep -rnE "createElement\([[:space:]]*[\"']canvas[\"']|new[[:space:]]+OffscreenCanvas" "$dir" --include='*.js' 2>/dev/null \
        | grep -vE "$code" | sed 's/^/9:/' || true
    for f in $(grep -rlE 'vp\.island\(' "$dir" --include='*.js' 2>/dev/null || true); do
        grep -nE 'addEventListener\(|setInterval\(|setTimeout\(|requestAnimationFrame\(|new[[:space:]]+(Resize|Mutation|Intersection|Performance)Observer' "$f" \
            | grep -vE '^[0-9]+:[[:space:]]*(//|/\*|\*)' | sed "s|^|10:$f:|" || true
    done
}

# --- 11–12. Сначала Firefox ---------------------------------------------------
# Firefox — браузер рабочего стола самого шлюза, и отрисовка там часто
# программная. Что работает в нём, работает везде; обратное неверно.
#   11 стили: свойства, которые Firefox не знает (zoom, overflow: overlay,
#      полоса прокрутки через ::-webkit-scrollbar) или за которые платит
#      каждый кадр и каждым слоем (will-change, background-attachment: fixed,
#      бесконечная анимация);
#   12 сценарии: возможности одного семейства браузеров как опора логики,
#      стиль строкой мимо политики содержимого, дорогие операции полотна при
#      программной отрисовке.
scan_styles() {
    local dir="$1" f
    # Комментарии вырезаются целиком с сохранением номеров строк: в стилях
    # они многострочные, и по началу строки их не узнать. Первая редакция
    # узнавала — и самопроверка поймала её на собственной чистой фикстуре.
    for f in $(find "$dir" -name '*.css' 2>/dev/null | sort); do
        perl -0pe 's{/\*.*?\*/}{ ($_ = $&) =~ s/[^\n]//g; $_ }gse' "$f" \
            | grep -nE 'will-change|background-attachment:[[:space:]]*fixed|(^|[[:space:];{])zoom:|overflow(-[xy])?:[[:space:]]*overlay|::-webkit-scrollbar|animation[^;]*infinite' \
            | sed "s|^|11:$f:|" || true
    done
}
scan_gecko() {
    local dir="$1"
    grep -rnE "performance\.memory|navigator\.connection|navigator\.deviceMemory|webkit[A-Z][A-Za-z]+\(|setAttribute\([[:space:]]*[\"']style[\"']|shadowBlur|getImageData|ctx\.filter|\.filter[[:space:]]*=[[:space:]]*[\"']" "$dir" --include='*.js' 2>/dev/null \
        | grep -vE '^[^:]+:[0-9]+:[[:space:]]*(//|/\*|\*)' | sed 's/^/12:/' || true
}

# Самопроверка: страж, который не умеет краснеть, хуже отсутствующего.
FIX="scripts/testdata/check-ui"
if ! scan_styles "$FIX/bad-11" | grep -q '^11:'; then
    say "самопроверка стража: фикстура $FIX/bad-11 не дала нарушения 11 — проверка 11 сломана"
fi
if ! scan_gecko "$FIX/bad-12" | grep -q '^12:'; then
    say "самопроверка стража: фикстура $FIX/bad-12 не дала нарушения 12 — проверка 12 сломана"
fi
out="$(scan_styles "$FIX/good"; scan_gecko "$FIX/good")"
if [ -n "$out" ]; then
    say "самопроверка стража: чистая фикстура $FIX/good дала нарушение 11–12:"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi
for n in 8 9 10; do
    if ! scan_scripts "$FIX/bad-$n" | grep -q "^$n:"; then
        say "самопроверка стража: фикстура $FIX/bad-$n не дала нарушения $n — проверка $n сломана"
    fi
done
out="$(scan_scripts "$FIX/good")"
if [ -n "$out" ]; then
    say "самопроверка стража: чистая фикстура $FIX/good дала нарушение:"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi

out="$(scan_scripts "$JS")"
if [ -n "$out" ]; then
    say "сценарий нарушает контракт памяти страницы (полотна и подписки — только через ядро островов):"
    printf '%s\n' "$out" | sed -E 's/^8:/      разметка строкой: /; s/^9:/      полотно создаёт сценарий: /; s/^10:/      вход острова мимо ядра: /' >&2
    echo "      → разметку и полотно отдаёт сервер; подписки, таймеры и кадры — через ядро (h.on, h.every, h.after, h.redraw)" >&2
fi

out="$(scan_styles "$CSS"; scan_gecko "$JS")"
if [ -n "$out" ]; then
    say "интерфейс не переживёт Firefox (только возможности, общие для всех движков):"
    printf '%s\n' "$out" | sed -E 's/^11:/      стиль: /; s/^12:/      сценарий: /' >&2
    echo "      → только возможности, общие для всех движков; лишнее — улучшением с проверкой наличия" >&2
fi

# Сценарий острова обязан быть отложенным: иначе он исполнится раньше ядра.
for f in $(grep -rlE 'vp\.island\(' "$JS" --include='*.js' 2>/dev/null || true); do
    name="$(basename "$f")"
    out="$(grep -rnE "<script[^>]*src=\"[^\"]*/$name\"" "$VIEWS" 2>/dev/null | grep -v ' defer' || true)"
    if [ -n "$out" ]; then
        say "сценарий острова $name подключён без defer — исполнится раньше ядра островов:"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
    fi
done

# --- 13–15. Масштабируемость: единица по роли, число по шкале ---------------
# Беда не в пикселях: «.45rem» — такой же хардкод, как «7px», просто красивее.
# Поэтому ниже маркера токенов число вообще не пишется руками: размер приходит
# из шкалы через var() или выводится calc(). Исключение — линия толщиной в
# пиксель и кольцо фокуса: это физические величины, в rem они мылятся.
#   13 размер мимо шкалы в правилах;
#   14 контрольная точка вне реестра или записанная в пикселях: в пикселях она
#      не учитывает увеличенный шрифт, и узкая раскладка включается позже, чем
#      текст начинает налезать;
#   15 решение о раскладке в шаблоне страницы: ряд карточек и число колонок
#      знает примитив (components/*-grid), а не страница.
BP='48em|64em|75em'          # реестр контрольных точек — шапка public/css/app.css
LAYOUT='chart-grid|status-lines|overview-blocks|metrics'  # ряды на атомах-примитивах
# field-grid пока законен: формы ещё не переведены на атомы.

scan_scale() {
    local f="$1" marker body
    marker="$(token_end "$f")"
    [ -n "$marker" ] || { echo "13:не найдены блоки токенов :root — шкалу проверить нечем"; return 0; }
    body="$(tail -n +"$marker" "$f" | perl -0pe 's{/\*.*?\*/}{ ($_ = $&) =~ s/[^\n]//g; $_ }gse')"
    # Пороги контейнерных запросов — отдельный случай: переменные в них не
    # работают так же, как в медиазапросах, поэтому число пишется буквально,
    # но обязано совпадать со ступенью шкалы ширин.
    printf '%s\n' "$body" | grep -vE '@container' | grep -nE '[0-9.]+rem' | sed 's/^/13:размер мимо шкалы: /' || true
    printf '%s\n' "$body" | grep -nE '@container[^{]*[0-9]' | grep -vE '(11|16|24|30|52)rem' | sed 's/^/13:порог контейнера мимо шкалы ширин: /' || true
    printf '%s\n' "$body" | grep -nE '[0-9.]+px' | grep -vE ':[^:]*\b[12]px\b' | sed 's/^/13:пиксели мимо линии: /' || true
    printf '%s\n' "$body" | grep -nE '@media[^{]*\(([a-z-]+-width|width): *[0-9.]+px' | sed 's/^/14:точка в пикселях: /' || true
    printf '%s\n' "$body" | grep -nE '@media[^{]*\(([a-z-]+-width|width):' | grep -vE "$BP" | sed 's/^/14:точка вне реестра: /' || true
}

# Самопроверка: страж, который не умеет краснеть, хуже отсутствующего.
if ! scan_scale "$FIX/bad-13/page.css" | grep -q '^13:'; then
    say "самопроверка стража: фикстура $FIX/bad-13 не дала нарушения 13 — проверка сломана"
fi
if ! scan_scale "$FIX/bad-14/page.css" | grep -q '^14:'; then
    say "самопроверка стража: фикстура $FIX/bad-14 не дала нарушения 14 — проверка сломана"
fi
out="$(scan_scale "$FIX/good/scale.css")"
if [ -n "$out" ]; then
    say "самопроверка стража: чистая фикстура дала нарушение 13–14:"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
fi

out="$(scan_scale "$CSS/app.css")"
if [ -n "$out" ]; then
    say "размер мимо шкалы или контрольная точка вне реестра (число — ступень шкалы или calc() из них; точки — 48em, 64em, 75em):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
    echo "      → размер берётся из шкалы var(--…) или выводится calc(); точек ровно три: $BP" >&2
fi

# --- 16. Имя, занятое и переменной, и функцией -------------------------------
# Объявление переменной побеждает объявление функции с тем же именем, и вызов
# такой «функции» бросает ошибку. Однажды таймер дебаунса назвали так же, как
# функцию остановки островов, — предохранитель
# срабатывал, но остановку до конца не доводил: ни плашки, ни освобождения
# полотен. Тихая ошибка, которую видно только на пути, где всё уже плохо.
for f in "$JS"/*.js; do
    # Сравниваются имена, объявленные на ОДНОМ уровне вложенности (отступ —
    # достаточный признак области в нашем стиле): «var x» внутри одной функции
    # и «function x» внутри другой друг другу не мешают.
    dup="$(comm -12 \
        <(grep -oE '^ *(var|let|const) [A-Za-z_$][A-Za-z0-9_$]*' "$f" \
            | sed -E 's/^( *)(var|let|const) /\1/' | awk '{ n = index($0, substr($0, length($0) - length($1) + 1)); print length($0) - length($1) "|" $1 }' | LC_ALL=C sort -u) \
        <(grep -oE '^ *function [A-Za-z_$][A-Za-z0-9_$]*' "$f" \
            | sed -E 's/^( *)function /\1/' | awk '{ print length($0) - length($1) "|" $1 }' | LC_ALL=C sort -u))"
    if [ -n "$dup" ]; then
        say "в $f имя занято и переменной, и функцией в одной области — вызов такой функции падает:"
        printf '%s\n' "$dup" | sed 's/^[0-9]*|/      /' >&2
    fi
done

out="$(grep -rnE "class=\"[^\"]*($LAYOUT)" "$VIEWS" --include='*.tmpl' 2>/dev/null | grep -v "$VIEWS/components/" || true)"
if [ -n "$out" ]; then
    say "страница решает вопросы раскладки (ряд карточек собирает атом-примитив):"
    printf '%s\n' "$out" | sed 's/^/      /' >&2
    echo "      → ряд карточек собирает примитив: components/chart-grid, status-grid, card-grid, metric-grid" >&2
fi

if [ "$fail" != 0 ]; then
    echo "" >&2
    echo "Интерфейс нарушает правила — исправьте места выше." >&2
    exit 1
fi
echo "check-ui: интерфейс по конституции"
