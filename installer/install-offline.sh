#!/bin/sh
# Установка панели с носителя на уже стоящую Ubuntu — без интернета.
#
# Одна строка на сервере, флешка с комплектом вставлена:
#   sudo mount -r /dev/disk/by-id/usb-*part1 /mnt && sudo sh /mnt/vpn-panel/install.sh
#
# Что делает сценарий (и ничего сверх этого): проверяет, что система
# подходит; копирует репозиторий с носителя во временный каталог; ставит
# пакет штатным менеджером только из этой копии; убирает копию и временный
# источник. Сеть, файрвол и службы не трогает — этим займётся сама панель
# после установки, по вашей команде. Диск этим способом не шифруется.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO=/var/cache/vpn-panel-media
LIST=/etc/apt/vpn-panel-media.list

say() { printf '\n%s\n' "$*"; }
fail() { printf '\nОшибка: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" = "0" ] || fail "запустите с правами администратора: sudo sh $0"
[ -f "$HERE/media.info" ] && [ -f "$HERE/repo/Packages" ] \
    || fail "рядом со сценарием нет комплекта (media.info, repo): запускайте его с носителя панели"

want="$(sed -n 's/^ubuntu=//p' "$HERE/media.info")"
version="$(sed -n 's/^version=//p' "$HERE/media.info")"
. /etc/os-release 2>/dev/null || fail "не удалось определить систему"
[ "${ID:-}" = "ubuntu" ] || fail "панель рассчитана на Ubuntu; у вас ${PRETTY_NAME:-неизвестная система}"
[ "${VERSION_ID:-}" = "$want" ] \
    || fail "носитель собран для Ubuntu $want, а у вас ${VERSION_ID:-?}: возьмите носитель своей версии или поставьте Ubuntu $want"
[ "$(dpkg --print-architecture)" = "amd64" ] || fail "поддерживается только архитектура amd64"

say "Что будет сделано"
cat <<TXT
  1. Пакеты с носителя скопированы во временный каталог
  2. Установлена панель управления шлюзом $version — только из этой копии,
     интернет не нужен
  3. Временный каталог и источник убраны

Ничего другого сценарий не делает: настройки сети, файрвола и служб он не
трогает. Диск этим способом не шифруется.
TXT

say "Копирую пакеты с носителя"
rm -rf "$REPO"
mkdir -p "$REPO"
cp -a "$HERE/repo/." "$REPO/"
# Носитель — локальные файлы, его подлинность несёт контрольная сумма самого
# носителя. Подпись и даты здесь только мешали бы: истёкший ключ или сбитые
# часы сервера остановили бы установку без сети.
echo "deb [trusted=yes check-date=no check-valid-until=no] file:$REPO ./" > "$LIST"
O="-o Dir::Etc::SourceList=$LIST -o Dir::Etc::SourceParts=/nonexistent"

say "Устанавливаю панель"
export DEBIAN_FRONTEND=noninteractive
# shellcheck disable=SC2086
apt-get $O -qq update
# shellcheck disable=SC2086
if ! apt-get $O install -y --no-install-recommends vpn-panel; then
    rm -rf "$REPO" "$LIST"
    fail "панель не установилась — подробности выше; носитель можно записать заново и повторить"
fi
rm -rf "$REPO" "$LIST"

say "Готово"
cat <<TXT
Панель $version установлена и уже работает. Флешку можно вынуть. Дальше:

  1. Выполните: sudo vpn-panel-code
     Команда напечатает код входа и адрес, по которому панель открыта в
     локальной сети. Нет сети — соедините ноутбук с сервером одним
     кабелем: адрес появится через минуту.
  2. Откройте этот адрес в браузере любого компьютера и введите код.

Если панель в браузере не открывается, шлюзом можно управлять с консоли:
  sudo vpn-panel

Обновления придут из источника проекта, как только у шлюза появится
интернет, и будут проверяться подписью.
TXT
